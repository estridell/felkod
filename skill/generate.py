#!/usr/bin/env python3
"""Writes skill/SKILL.md from the felkod CLI's own --help output, so the skill is a plain reference."""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLI = ROOT / "cli" / "felkod"
COMMANDS = ["status", "daemon", "ident", "faults", "jobs", "run", "read", "log", "bench", "ds2", "sessions", "session"]


def help_text(*args):
    return subprocess.run([sys.executable, str(CLI), *args, "--help"], capture_output=True, text=True, check=True).stdout


def main():
    parts = [
        "---",
        "name: felkod",
        "description: felkod CLI reference (BMW E46 / Siemens MS43 diagnostics over a K+DCAN cable): commands, options, output format.",
        "---",
        "",
        "# felkod",
        "",
        f"Generated by `skill/generate.py` from `{CLI.relative_to(ROOT)} --help`. Do not edit by hand.",
        "",
        "```",
        help_text().rstrip(),
        "```",
    ]
    for command in COMMANDS:
        parts += ["", f"## felkod {command}", "", "```", help_text(command).rstrip(), "```"]
    (ROOT / "skill" / "SKILL.md").write_text("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
